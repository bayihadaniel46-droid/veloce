const express = require("express");
const authMiddleware = require("../middleware/authMiddleware");
const { listClans, createClan, addClanMembers, listClanMessages, openClanMessage, revealClanSender, sendClanMessage } = require("../controllers/clanController");
const { listVotes, createVote, castVote } = require("../controllers/clanVoteController");
const clanHub = require("../controllers/clanHubController");
const { parseMessageFiles } = require("../middleware/messageUploads");
const requireCommunityRules = require("../middleware/requireCommunityRules");

const router = express.Router();
router.use(authMiddleware);
router.get("/discover", clanHub.discoverClans);
router.get("/knowledge", clanHub.getKnowledge);
router.post("/knowledge/:documentId/purchase", clanHub.purchaseKnowledge);
router.get("/", listClans);
router.post("/", requireCommunityRules, createClan);
router.post("/:clanId/join", clanHub.requestToJoin);
router.patch("/:clanId/settings", clanHub.updateClanSettings);
router.put("/:clanId/roles", clanHub.assignClanRole);
router.get("/:clanId/requests", clanHub.listMembershipRequests);
router.post("/:clanId/requests/:userId/review", clanHub.reviewMembershipRequest);
router.post("/:clanId/rating", clanHub.rateClan);
router.get("/:clanId/knowledge", clanHub.getKnowledge);
router.post("/:clanId/knowledge", requireCommunityRules, clanHub.createKnowledge);
router.get("/:clanId/assistant-knowledge", clanHub.listAssistantKnowledge);
router.post("/:clanId/assistant-knowledge", requireCommunityRules, clanHub.publishAssistantKnowledge);
router.post("/:clanId/contributions", requireCommunityRules, clanHub.contributeToClan);
router.post("/:clanId/distributions", clanHub.distributeClanRevenue);
router.post("/:clanId/members", addClanMembers);
router.get("/:clanId/votes", listVotes);
router.post("/:clanId/votes", requireCommunityRules, createVote);
router.post("/:clanId/votes/:voteId/cast", requireCommunityRules, castVote);
router.get("/:clanId/messages", listClanMessages);
router.post("/:clanId/messages", requireCommunityRules, parseMessageFiles, sendClanMessage);
router.post("/:clanId/messages/:messageId/open", openClanMessage);
router.post("/:clanId/messages/:messageId/reveal", revealClanSender);

module.exports = router;
